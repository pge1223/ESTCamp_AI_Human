def _read_rule_file(rule_name: str) -> str:
    path = _RULE_DIR / f"{rule_name}.txt"
    try:
        return path.read_text(encoding="utf-8").strip()
    except FileNotFoundError:
        return ""


def _remove_examples(rule_text: str) -> str:
    if "[예시]" not in rule_text:
        return rule_text
    return rule_text.split("[예시]", 1)[0].strip()


def load_persona_rule(persona_id: str, compact: bool = False) -> str:
    """
    공통 규칙 + 선택된 페르소나 규칙만 반환.
    외부 규칙 파일이 있으면 파일을 우선 사용하고, 없으면 내장 규칙으로 폴백한다.
    compact=True면 예시 섹션을 제외해 캐릭터 대화 모드 토큰을 줄인다.
    """
    common = _read_rule_file("common") or _COMMON_STYLE_RULE
    persona = _read_rule_file(persona_id) or _PERSONA_STYLE_RULES.get(persona_id, "")

    if compact:
        common = _remove_examples(common)
        persona = _remove_examples(persona)

    return f"{common.strip()}\n\n{persona.strip()}".strip()


